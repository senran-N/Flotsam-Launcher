const dictionaries: Record<Locale, Record<string, string>> = { zh, en };
const locale = ref<Locale>('zh');

export function useLocale() {
  return {
    locale,
    setLocale(next: Locale) {
      locale.value = next === 'en' ? 'en' : 'zh';
      document.documentElement.lang = locale.value === 'en' ? 'en' : 'zh-CN';
    },
    t,
  };
}
export function t(key: keyof typeof zh, values?: Record<string, string | number>): string {
  const text = dictionaries[locale.value][key] ?? dictionaries.zh[key] ?? key;
  if (!values) return text;
  return text.replace(/\{(\w+)\}/g, (_, name: string) =>
    values[name] === undefined ? `{${name}}` : String(values[name]),
  );
}
export const tr = (key: keyof typeof zh, values?: Record<string, string | number>) =>
  computed(() => t(key, values));
